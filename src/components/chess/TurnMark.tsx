import { cn } from "@/components/ui";

/**
 * Квадратик «чей ход» рядом со словами: белый — ходят белые, чёрный — ходят чёрные.
 *
 * Тот же знак, что в углу рамки доски и на диаграммах в шахматных книгах (□ и ■). На экранах, где доска стоит
 * без рамки (телефон, раскладка «доска слева»), знака в углу нет — он переезжает к подписи: кто ходит, видно
 * с одного взгляда, не читая. Слова остаются: цвет — не единственный признак, а экранный диктор читает подпись.
 *
 * Размер — от шрифта подписи; серая рамка видна и на светлой, и на тёмной теме при любом цвете квадратика.
 */
export function TurnMark({ side, className }: { side: "w" | "b"; className?: string }) {
  return (
    <span
      aria-hidden
      data-turn-mark={side}
      className={cn(
        "inline-block h-[1.15em] w-[1.15em] shrink-0 rounded-[0.22em] border-2 border-muted align-[-0.2em]",
        side === "w" ? "bg-white" : "bg-[#111827]",
        className,
      )}
    />
  );
}
