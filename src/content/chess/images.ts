export const CHESS_IMAGES: ChessImage[] = manifest.images.map((m) => ({
  ...m,
  ...(CAPTIONS[m.id] ?? { kind: "art" as ImageKind, caption: m.title, alt: m.title }),
}));

const BY_ID = new Map(CHESS_IMAGES.map((i) => [i.id, i]));

export function chessImage(id: string): ChessImage | undefined {
  return BY_ID.get(id);
}

/** Картинки по списку id — те, что есть на диске. */
export function chessImages(ids: string[] | undefined): ChessImage[] {
  return (ids ?? []).map((id) => BY_ID.get(id)).filter((i): i is ChessImage => !!i);
}

export function isPublicDomain(img: Pick<ChessImage, "licenseCode">): boolean {
  return /^(pd|cc0)/.test(img.licenseCode);
}

/** Строка авторства: «Фото: Frans Peeters · CC BY-SA 2.0» или «Общественное достояние». */
export function imageCredit(img: ChessImage): string {
  const what =
    img.kind === "art" ? "" : img.kind === "person" || img.kind === "place" || img.kind === "object" ? "Фото: " : "";
  if (isPublicDomain(img)) {
    const by = img.author && !/unknown|неизвест/i.test(img.author) ? `${img.author} · ` : "";
    return `${what}${by}${img.licenseCode === "cc0" ? "CC0" : "общественное достояние"}`;
  }
  return `${what}${img.author || "автор неизвестен"} · ${img.license}`;
}
