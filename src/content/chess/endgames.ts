/**
 * Школа эндшпиля: король и пешка против короля. Все позиции проверяются точной таблицей
 * (src/lib/engine/kpk.ts): тесты сверяют, что ответ «догонит / не догонит», единственный
 * верный ход и цель практики совпадают с настоящим результатом позиции.
 */

export type EndgameDrillKind = "square" | "find" | "play";

export interface EndgameDrill {
  /** Стабильный идентификатор — по нему хранится прогресс. */
  id: string;
  kind: EndgameDrillKind;
  fen: string;
  /** Условие для ребёнка. */
  prompt: string;
  hint?: string;
  /** Объяснение после решения. */
  why: string;
  /** Практика: провести пешку в ферзи или удержать ничью. */
  goal?: "promote" | "hold";
}

export interface EndgameLesson {
  id: string;
  emoji: string;
  title: string;
  /** Главная мысль урока одной строкой. */
  idea: string;
  text: string[];
  demo?: { fen: string; highlight?: string[]; caption: string };
  drills: EndgameDrill[];
}

