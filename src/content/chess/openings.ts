/**
 * Дебюты: как начинать партию. Ходы — в международной записи, каждая линия проверяется тестами.
 */
export type OpeningCategory = "open" | "semiOpen" | "closed" | "gambit" | "trap";

export interface Opening {
  id: string;
  name: string;
  /** Код по шахматной энциклопедии дебютов. */
  eco: string;
  category: OpeningCategory;
  /** За кого удобно изучать линию в тренажёре. */
  side: "white" | "black";
  /** Сложность: 1 — самый простой. */
  stars: 1 | 2 | 3;
  moves: string[];
  /** Главная идея — одной фразой. */
  idea: string;
  /** Что происходит в этих ходах и как играть дальше. */
  plan: string[];
  facts: string[];
  /** Кто из великих играл этот дебют. */
  playedBy?: string;
  /** Картинка к истории дебюта (id из images.ts). */
  image?: string;
}

