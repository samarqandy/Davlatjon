export interface ChessPuzzle {
  id: string;
  theme: PuzzleTheme;
  /** Сложность: 1 — самая простая, 5 — олимпиадная. */
  stars: 1 | 2 | 3 | 4 | 5;
  fen: string;
  /** Мат за столько ходов; принимается любой ход, который ведёт к форсированному мату. */
  mateIn?: 1 | 2 | 3;
  /** Для задач на выигрыш материала: принимаемые ходы (запись «e2e4»). */
  solution?: string[];
  title: string;
  hint: string;
  explanation: string;
  source?: string;
}

