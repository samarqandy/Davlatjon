/** Число зёрен на клетке n (1…64) и сумма на всех клетках до неё. */
export function grainsOn(square: number): bigint {
  return BigInt(1) << BigInt(square - 1);
}

export function grainsUpTo(square: number): bigint {
  return (BigInt(1) << BigInt(square)) - BigInt(1);
}

/** Число с пробелами между тысячами: 18 446 744 073 709 551 615. */
export function formatBig(n: bigint): string {
  return n.toString().replace(/\B(?=(\d{3})+(?!\d))/g, " ");
}

/** Ходы коня с клетки (0…63, a1 = 0) — для игры «Путешествие коня». */
export function knightMoves(sq: number): number[] {
  const f = sq % 8;
  const r = Math.floor(sq / 8);
  const out: number[] = [];
  for (const [df, dr] of [
    [1, 2],
    [2, 1],
    [2, -1],
    [1, -2],
    [-1, -2],
    [-2, -1],
    [-2, 1],
    [-1, 2],
  ]) {
    const nf = f + df;
    const nr = r + dr;
    if (nf >= 0 && nf < 8 && nr >= 0 && nr < 8) out.push(nr * 8 + nf);
  }
  return out;
}

/** Правило Варнсдорфа: из доступных клеток лучше те, откуда дальше меньше всего ходов. */
export function warnsdorffBest(sq: number, visited: Set<number>): number[] {
  const options = knightMoves(sq).filter((s) => !visited.has(s));
  if (!options.length) return [];
  const degree = (s: number) => knightMoves(s).filter((t) => !visited.has(t) && t !== s).length;
  const min = Math.min(...options.map(degree));
  return options.filter((s) => degree(s) === min);
}

export function squareName(sq: number): string {
  return "abcdefgh"[sq % 8] + String(Math.floor(sq / 8) + 1);
}
